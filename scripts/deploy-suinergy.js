#!/usr/bin/env node

/**
 * Deployment script for Suinergy contracts
 * Usage: node scripts/deploy-suinergy.js <network>
 * Networks: testnet, devnet, mainnet
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const network = process.argv[2] || 'testnet';
const contractsDir = path.join(__dirname, '../packages/contracts/suinergy');

console.log(`🚀 Deploying Suinergy contracts to ${network}...\n`);

// Check if Sui CLI is installed
try {
    execSync('sui --version', { stdio: 'ignore' });
} catch (error) {
    console.error('❌ Sui CLI not found. Please install it first:');
    console.error('   cargo install --locked --git https://github.com/MystenLabs/sui.git --branch devnet sui');
    process.exit(1);
}

// Build contracts
console.log('📦 Building contracts...');
try {
    execSync('sui move build', { 
        cwd: contractsDir,
        stdio: 'inherit'
    });
    console.log('✅ Build successful\n');
} catch (error) {
    console.error('❌ Build failed');
    process.exit(1);
}

// Deploy to network
console.log(`📤 Deploying to ${network}...`);
let deployOutput;
try {
    // Environment should already be set via sui client active-env
    // No need to switch
    
    deployOutput = execSync(`sui client publish --gas-budget 100000000 --json`, {
        cwd: contractsDir,
        encoding: 'utf8'
    });
    console.log('✅ Deployment successful\n');
} catch (error) {
    console.error('❌ Deployment failed');
    console.error(error.message);
    process.exit(1);
}

// Parse deployment output
let deploymentData;
try {
    deploymentData = JSON.parse(deployOutput);
} catch (error) {
    console.error('❌ Failed to parse deployment output');
    console.error(deployOutput);
    process.exit(1);
}

const packageId = deploymentData.objectChanges?.find(
    change => change.type === 'published'
)?.packageId;

if (!packageId) {
    console.error('❌ Could not find package ID in deployment output');
    console.error(JSON.stringify(deploymentData, null, 2));
    process.exit(1);
}

console.log('📋 Deployment Results:');
console.log(`   Package ID: ${packageId}\n`);

// Initialize registry
console.log('🔧 Initializing Protocol Registry...');
let registryOutput;
try {
    registryOutput = execSync(
        `sui client call --package ${packageId} --module registry --function init --gas-budget 10000000 --json`,
        { encoding: 'utf8' }
    );
    const registryData = JSON.parse(registryOutput);
    
    // Find ProtocolConfig from created objects
    const configId = registryData.objectChanges?.find(
        change => change.type === 'created' && (
            change.objectType?.includes('ProtocolConfig') || 
            change.objectType?.includes('protocol_config')
        )
    )?.objectId;
    
    // Also check effects for created objects
    const createdObjects = registryData.effects?.created || [];
    const configFromEffects = createdObjects.find(
        obj => obj.owner?.Shared || obj.reference?.objectId
    );
    
    if (configId) {
        console.log(`   Config ID: ${configId}\n`);
        
        // Initialize vault for SUI
        console.log('🔧 Initializing SUI Vault...');
        let vaultOutput;
        try {
            vaultOutput = execSync(
                `sui client call --package ${packageId} --module vault --function init_vault --type-args "0x2::sui::SUI" --gas-budget 10000000 --json`,
                { encoding: 'utf8' }
            );
            const vaultData = JSON.parse(vaultOutput);
            const vaultId = vaultData.objectChanges?.find(
                change => change.type === 'created' && change.objectType?.includes('Vault')
            )?.objectId;
            
            if (vaultId) {
                console.log(`   Vault ID: ${vaultId}\n`);
                
                // Write to .env.local
                const envPath = path.join(__dirname, '../apps/dapp/.env.local');
                const envContent = `# Suinergy dApp Environment Variables
# Generated by deployment script

NEXT_PUBLIC_SUI_NETWORK=${network}
NEXT_PUBLIC_SUINERGY_PACKAGE_ID=${packageId}
NEXT_PUBLIC_VAULT_ID=${vaultId}
NEXT_PUBLIC_PROTOCOL_CONFIG_ID=${configId}

# Coin Types (update with actual Testnet addresses when available)
NEXT_PUBLIC_USDC_COIN_TYPE=
NEXT_PUBLIC_USDT_COIN_TYPE=

# Backend API URL
NEXT_PUBLIC_API_URL=http://localhost:4000
`;
                
                fs.writeFileSync(envPath, envContent);
                console.log('✅ Environment variables written to apps/dapp/.env.local\n');
                console.log('📝 Next steps:');
                console.log('   1. Restart your dev server: pnpm dev');
                console.log('   2. The deposit modal should now work!');
            } else {
                console.error('❌ Could not find Vault ID');
            }
        } catch (error) {
            console.error('❌ Failed to initialize vault');
            console.error(error.message);
        }
    } else {
        console.error('❌ Could not find Config ID');
    }
} catch (error) {
    console.error('❌ Failed to initialize registry');
    console.error(error.message);
    console.log('\n📝 Manual initialization required:');
    console.log(`   sui client switch --env ${network}`);
    console.log(`   sui client call --package ${packageId} --module registry --function init --gas-budget 10000000`);
}

console.log('\n✅ Deployment complete!');

